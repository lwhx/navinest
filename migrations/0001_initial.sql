PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS users (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	email TEXT UNIQUE,
	username TEXT NOT NULL UNIQUE,
	display_name TEXT NOT NULL,
	password_hash TEXT,
	avatar_file_id INTEGER,
	cover_file_id INTEGER,
	role TEXT NOT NULL DEFAULT 'user',
	status TEXT NOT NULL DEFAULT 'active',
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS oauth_accounts (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	provider TEXT NOT NULL,
	provider_user_id TEXT NOT NULL,
	provider_username TEXT,
	access_token_encrypted TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(provider, provider_user_id)
);

CREATE TABLE IF NOT EXISTS files (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
	bucket TEXT NOT NULL,
	object_key TEXT NOT NULL UNIQUE,
	public_url TEXT,
	mime_type TEXT,
	size INTEGER,
	width INTEGER,
	height INTEGER,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	type TEXT NOT NULL DEFAULT 'site',
	parent_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	slug TEXT NOT NULL,
	icon TEXT,
	description TEXT,
	sort_order INTEGER NOT NULL DEFAULT 0,
	is_visible INTEGER NOT NULL DEFAULT 1,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(type, slug)
);

CREATE TABLE IF NOT EXISTS tags (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	type TEXT NOT NULL DEFAULT 'site',
	name TEXT NOT NULL,
	slug TEXT NOT NULL,
	description TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(type, slug)
);

CREATE TABLE IF NOT EXISTS items (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	type TEXT NOT NULL DEFAULT 'site',
	category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
	author_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
	title TEXT NOT NULL,
	slug TEXT NOT NULL,
	summary TEXT,
	content TEXT,
	cover_file_id INTEGER REFERENCES files(id) ON DELETE SET NULL,
	icon_file_id INTEGER REFERENCES files(id) ON DELETE SET NULL,
	status TEXT NOT NULL DEFAULT 'published',
	visibility TEXT NOT NULL DEFAULT 'public',
	sort_order INTEGER NOT NULL DEFAULT 0,
	is_featured INTEGER NOT NULL DEFAULT 0,
	published_at TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(type, slug)
);

CREATE TABLE IF NOT EXISTS item_meta (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
	meta_key TEXT NOT NULL,
	meta_value TEXT,
	UNIQUE(item_id, meta_key)
);

CREATE TABLE IF NOT EXISTS item_tags (
	item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
	tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
	PRIMARY KEY (item_id, tag_id)
);

CREATE TABLE IF NOT EXISTS favorites (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(user_id, item_id)
);

CREATE TABLE IF NOT EXISTS footprints (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
	visited_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS custom_categories (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	parent_id INTEGER REFERENCES custom_categories(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	icon TEXT,
	sort_order INTEGER NOT NULL DEFAULT 0,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS custom_links (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	category_id INTEGER REFERENCES custom_categories(id) ON DELETE SET NULL,
	title TEXT NOT NULL,
	url TEXT NOT NULL,
	icon_url TEXT,
	summary TEXT,
	sort_order INTEGER NOT NULL DEFAULT 0,
	status TEXT NOT NULL DEFAULT 'active',
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS submissions (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	target_item_id INTEGER REFERENCES items(id) ON DELETE SET NULL,
	type TEXT NOT NULL,
	title TEXT NOT NULL,
	payload_json TEXT NOT NULL,
	status TEXT NOT NULL DEFAULT 'pending',
	reviewer_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
	review_message TEXT,
	reviewed_at TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	sender_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
	type TEXT NOT NULL DEFAULT 'system',
	title TEXT NOT NULL,
	content TEXT,
	data_json TEXT,
	is_read INTEGER NOT NULL DEFAULT 0,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stats_daily (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
	date TEXT NOT NULL,
	views INTEGER NOT NULL DEFAULT 0,
	likes INTEGER NOT NULL DEFAULT 0,
	favorites INTEGER NOT NULL DEFAULT 0,
	comments INTEGER NOT NULL DEFAULT 0,
	downloads INTEGER NOT NULL DEFAULT 0,
	UNIQUE(item_id, date)
);

CREATE TABLE IF NOT EXISTS home_modules (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	type TEXT NOT NULL,
	title TEXT NOT NULL,
	config_json TEXT NOT NULL DEFAULT '{}',
	sort_order INTEGER NOT NULL DEFAULT 0,
	is_enabled INTEGER NOT NULL DEFAULT 1,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS search_engines (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	group_key TEXT NOT NULL,
	name TEXT NOT NULL,
	key TEXT NOT NULL UNIQUE,
	url_template TEXT NOT NULL,
	placeholder TEXT,
	sort_order INTEGER NOT NULL DEFAULT 0,
	is_enabled INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS hot_sources (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL,
	type TEXT NOT NULL,
	url TEXT NOT NULL,
	headers_json TEXT NOT NULL DEFAULT '{}',
	parser_json TEXT NOT NULL DEFAULT '{}',
	cache_ttl INTEGER NOT NULL DEFAULT 900,
	is_enabled INTEGER NOT NULL DEFAULT 1,
	last_fetch_at TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hot_items (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	source_id INTEGER NOT NULL REFERENCES hot_sources(id) ON DELETE CASCADE,
	rank INTEGER NOT NULL,
	title TEXT NOT NULL,
	url TEXT NOT NULL,
	hot_value TEXT,
	extra_json TEXT NOT NULL DEFAULT '{}',
	fetched_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS settings (
	key TEXT PRIMARY KEY,
	value_json TEXT NOT NULL,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_items_type_status_sort ON items(type, status, sort_order);
CREATE INDEX IF NOT EXISTS idx_items_category ON items(category_id);
CREATE INDEX IF NOT EXISTS idx_item_meta_key ON item_meta(meta_key);
CREATE INDEX IF NOT EXISTS idx_stats_daily_date ON stats_daily(date);
CREATE INDEX IF NOT EXISTS idx_hot_items_source_rank ON hot_items(source_id, rank);
